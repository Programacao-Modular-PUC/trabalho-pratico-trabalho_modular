package com.marau.marau.enums;

/**
 * Categorias do Programa de Fidelidade.
 * Clientes avançam de categoria conforme o número de hospedagens realizadas.
 *
 *  BRONZE   →  1 a 2 hospedagens
 *  PRATA    →  3 a 5 hospedagens
 *  OURO     →  6 a 9 hospedagens
 *  DIAMANTE → 10 ou mais hospedagens
 */
public enum CategoriaFidelidade {
    BRONZE,
    PRATA,
    OURO,
    DIAMANTE
}
